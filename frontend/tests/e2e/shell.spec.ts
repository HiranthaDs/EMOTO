import { expect, test } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

test('secure entry renders without horizontal overflow', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByText('EMOTO').first()).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  expect(overflow).toBe(false)
})

test('administrator can enter the workspace and use navigation', async ({ page }, testInfo) => {
  await page.goto('/')
  const authHeading = page.locator('.auth-card h2')
  await expect(authHeading).toBeVisible()
  await page.getByLabel('Email address').fill('admin@gmail.com')
  await page.getByLabel('Password').fill('admin@123')
  await page.getByRole('button', { name: 'Sign in securely' }).click()
  await expect(page.getByRole('heading', { name: 'BMW parts overview' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Switch to dark theme' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  const screenshotDir = path.resolve('../docs/screenshots')
  fs.mkdirSync(screenshotDir, { recursive: true })
  await page.screenshot({ path: path.join(screenshotDir, `${testInfo.project.name}.png`), fullPage: true })
  const menuButton = page.getByRole('button', { name: 'Open menu' })
  if (await menuButton.isVisible()) await menuButton.click()
  await page.getByRole('link', { name: 'Parts catalog' }).click()
  await expect(page.getByRole('heading', { name: 'Parts catalog' })).toBeVisible()
  await expect(page.getByRole('button', { name: /New part/i })).toBeVisible()
  await page.goto('/inventory')
  await expect(page.getByRole('heading', { name: 'Inventory control' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Update stock' })).toBeVisible()
  await expect(page.getByText('Inventory value')).toBeVisible()
  await page.getByRole('button', { name: 'Switch to light theme' }).click()
  await page.goto('/pos')
  await expect(page.getByRole('heading', { name: 'Point of sale' })).toBeVisible()
  await page.getByRole('button', { name: 'Create customer and BMW' }).click()
  const runId = `${testInfo.project.name}-${Date.now()}`
  await page.getByLabel('Customer name').fill(`POS Customer ${testInfo.project.name}`)
  await page.getByLabel('Phone number').fill('+94770000123')
  await page.getByLabel('Vehicle number').fill(`E2E-${runId}`.toUpperCase())
  await page.getByLabel('BMW model').fill('320d')
  await page.getByRole('button', { name: 'Save and use in POS' }).click()
  await expect(page.getByText(`POS Customer ${testInfo.project.name}`).first()).toBeVisible()
  await page.getByRole('button', { name: /Quotation/ }).click()
  await page.getByRole('button', { name: 'Custom workshop line' }).click()
  await page.getByLabel('Enter and save a new supplier manually').check()
  await page.getByLabel('Supplier company').fill(`E2E Supplier ${runId}`)
  await page.getByLabel('Contact person').fill('E2E Supplier Contact')
  await page.getByLabel('Customer requirement or work description').fill('Front air suspension diagnostic and replacement')
  await page.getByLabel('Customer price / unit (LKR)').fill('3500')
  await page.getByLabel('Private cost / unit (LKR)').fill('2000')
  await page.getByLabel('Overhead / unit (LKR)').fill('250')
  await page.getByRole('button', { name: 'Increase quantity' }).click()
  await page.getByRole('button', { name: 'Reduce quantity' }).click()
  await page.locator('input[name="warranty_value"]').fill('2')
  await page.locator('select[name="warranty_unit"]').selectOption('weeks')
  await page.getByRole('button', { name: 'Add another item or service' }).click()
  await page.getByLabel('Line type').nth(1).selectOption('service')
  await page.getByLabel('Customer requirement or work description').nth(1).fill('Workshop alignment and calibration')
  await page.getByLabel('Customer price / unit (LKR)').nth(1).fill('4500')
  await page.getByLabel('Private cost / unit (LKR)').nth(1).fill('1200')
  await page.getByLabel('Overhead / unit (LKR)').nth(1).fill('300')
  await page.locator('input[name="service_interval_value"]').fill('1')
  await page.locator('select[name="service_interval_unit"]').selectOption('years')
  await page.getByRole('button', { name: 'Add 2 lines to document' }).click()
  await expect(page.locator('.pos-line-description').nth(1)).toHaveValue('Workshop alignment and calibration')
  await expect(page.getByText(/Ends \d{4}-\d{2}-\d{2}/)).toBeVisible()
  await expect(page.getByRole('button', { name: 'Preview quotation' })).toBeEnabled()
  const posOverflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
  expect(posOverflow).toBe(false)
  await page.screenshot({ path: path.join(screenshotDir, `pos-${testInfo.project.name}.png`), fullPage: true })
  await page.getByRole('button', { name: 'Preview quotation' }).click()
  await expect(page.getByRole('heading', { name: 'Review before saving' })).toBeVisible()
  await expect(page.getByText('2 weeks warranty', { exact: false })).toBeVisible()
  await page.screenshot({ path: path.join(screenshotDir, `quotation-preview-${testInfo.project.name}.png`), fullPage: true })
  await page.getByRole('button', { name: 'Save quotation' }).click()
  await expect(page.getByRole('heading', { name: 'Quotation details' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Create secure link' })).toBeVisible()
})
